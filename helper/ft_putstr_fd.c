#include "../push_swap.h"

int	ft_putstr_fd(char *s, int fd)
{
	size_t	i;

	if (!s)
		return (-1);
	i = 0;
	while (s[i])
	{
		write(fd, s + i, 1);
		i++;
	}
	return (1);
}
